#ifndef RESURS_CRYPTO_H
#define RESURS_CRYPTO_H
/**
 * @file
 * @brief Internal C++ AES-256-GCM implementation and owned result types.
 * Java/JNA callers use wrapper.h rather than these C++ declarations.
 */
#include <iostream>
#include <stdint.h>
#include <openssl/evp.h>
#include <openssl/rand.h>
#include <array>
#include <vector>
#include <climits>
#include <stdexcept>
#include <memory>

#include "crypto_types.h"

/** Owns the ciphertext and the metadata required to authenticate and decrypt it. */
struct EncryptionResult
{
    /// Authentication tag for this ciphertext; store it with the IV and ciphertext.
    std::array<unsigned char, resurs::crypto::GCM_TAG_SIZE_BYTES> tag;
    /// Fresh random IV generated by the encrypt operation.
    std::array<unsigned char, resurs::crypto::GCM_IV_SIZE_BYTES> iv;
    /// Binary ciphertext with the same byte length as the original plaintext.
    std::vector<unsigned char> ciphertext;
};


/** Authentication failed: the supplied key, IV, tag, or ciphertext does not match. */
class AuthenticationError : public std::runtime_error
{
    public:
        /// Construct the error that the C wrapper maps to CRYPTO_AUTHENTICATION_FAILED.
        AuthenticationError() : std::runtime_error("authentication failed") {}
};


/** Owned plaintext container; the current decrypt method returns std::string directly. */
struct DecryptionResult
{
    /// Binary plaintext; embedded null bytes are part of the value.
    std::string plaintext;
};

/**
 * Owns an OpenSSL cipher context and the fetched AES-256-GCM algorithm.
 *
 * An instance can be reused for sequential operations. Its mutable context must
 * not be used concurrently; use separate instances or external synchronization.
 * Keys and input buffers remain caller-owned and are only borrowed during calls.
 * Internal methods rely on the documented input sizes; wrapper.h provides the
 * validated C ABI and translates exceptions into result codes.
 */
class AES256_Encryption
{
public:
    /**
     * Allocate the cipher context and fetch AES-256-GCM from OpenSSL.
     * Owned resources are released automatically, including if construction fails.
     * @throws std::runtime_error if allocation or algorithm lookup fails in OpenSSL.
     */
    AES256_Encryption() : ctx(EVP_CIPHER_CTX_new(), EVP_CIPHER_CTX_free), cipher(EVP_CIPHER_fetch(nullptr, "AES-256-GCM", nullptr), EVP_CIPHER_free)
    {
        if (ctx == nullptr)
        {
            throw std::runtime_error("failed to create cipher context");
        }

        if (cipher == nullptr)
        {
            throw std::runtime_error("failed to fetch aes-256-gcm");
        }
    };

    /**
     * Encrypt binary plaintext with a fresh random 12-byte IV and a 16-byte tag.
     *
     * @param plaintext Borrowed input, not modified despite the non-const reference.
     * Its byte length must fit in int for the OpenSSL update call. This internal
     * method does not reject empty input; the C wrapper does.
     * @param aes_key Non-null pointer to at least 32 readable key bytes.
     * @return Owned ciphertext, IV, and tag. Persist all three for decryption.
     * @throws std::runtime_error if IV generation or an OpenSSL operation fails.
     * Allocation failures may also propagate to the C wrapper.
     */
    EncryptionResult AES256_Encrypt(std::string& plaintext, const unsigned char *aes_key);

    /**
     * Authenticate and decrypt binary ciphertext after resetting the owned context.
     *
     * @param ciphertext Borrowed bytes whose length must fit in int.
     * @param aes_key Non-null pointer to at least 32 readable key bytes.
     * @param iv The original 12-byte encryption IV.
     * @param tag The original 16-byte authentication tag.
     * @return Owned binary plaintext, including any embedded null bytes, only
     * after authentication succeeds. No plaintext is returned on failure.
     * @throws AuthenticationError if final authentication fails.
     * @throws std::runtime_error if context setup or another OpenSSL operation fails.
     * Allocation failures may also propagate to the C wrapper.
     */
    std::string AES256_Decrypt(const std::vector<unsigned char> &ciphertext, const unsigned char *aes_key, const std::array<unsigned char, resurs::crypto::GCM_IV_SIZE_BYTES> &iv, const std::array<unsigned char, resurs::crypto::GCM_TAG_SIZE_BYTES> &tag);

private:
    /// Owns a mutable cipher context and releases it with EVP_CIPHER_CTX_free.
    using CipherCtxPtr = std::unique_ptr<EVP_CIPHER_CTX, decltype(&EVP_CIPHER_CTX_free)>;
    /// Owns the fetched algorithm and releases it with EVP_CIPHER_free.
    using CipherPtr = std::unique_ptr<EVP_CIPHER, decltype(&EVP_CIPHER_free)>;
    /// Per-instance encryption/decryption state, reused sequentially.
    CipherCtxPtr ctx;
    /// Algorithm fetched once during construction and reused for each operation.
    CipherPtr cipher;
};

#endif
